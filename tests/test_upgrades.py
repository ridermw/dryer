def test_prefix_filter_matches_brute_force_jaccard():
    rng = random.Random(7)
    vocab = [f"t{i}" for i in range(40)]
    entries = [
        Entry("python", f"f{i}.py", 1, 5, 25, frozenset(rng.sample(vocab, rng.randint(0, 12))))
        for i in range(120)
    ]
    for threshold in (0.0, 0.1, 1 / 3, 0.5, 0.8, 0.82, 0.99, 1.0):
        expected = [
            (left.file, right.file)
            for i, left in enumerate(entries)
            for right in entries[i + 1 :]
            if jaccard(left.fingerprints, right.fingerprints) >= threshold
        ]
        found = [(d.left.file, d.right.file) for d in find_duplicates(entries, threshold)]
        assert sorted(found) == sorted(expected), threshold


def test_typescript_inline_route_callbacks_compared_independently():
    src = """\
export function registerRoutes(app: any) {
  app.get("/a", (req: any, res: any) => {
    const user = lookup(req.id);
    const body = render(user);
    return res.send(body);
  });
  app.post("/b", (req: any, res: any) => {
    const item = lookup(req.id);
    const out = render(item);
    return res.send(out);
  });
}
"""
    entries, _ = entries_in_source("typescript", src, "routes.ts", "routes.ts")
    assert len(entries) == 3
    found = find_duplicates(entries, threshold=0.99)
    assert len(found) == 1
    assert (found[0].left.start_line, found[0].right.start_line) == (2, 7)


@pytest.mark.parametrize("value", ["nan", "inf", " -0.1", "1.1", "1e309"])
def test_invalid_threshold_rejected_before_scanning(value, monkeypatch, capsys):
    monkeypatch.setattr("dryer.cli.select_files", lambda _o: pytest.fail("must not scan"))
    assert run(["--threshold", value]) == 1
    assert "--threshold must be between 0 and 1" in capsys.readouterr().err


def test_threshold_accepts_bounds():
    assert parse_args(["--threshold", "0"]).threshold == 0.0
    assert parse_args(["--threshold", "1"]).threshold == 1.0


def test_parser_for_prefers_bundled_parser_before_download(monkeypatch):
    import tree_sitter_language_pack as tslp
    from dryer import treesitter

    treesitter.parser_for.cache_clear()
    downloads = []
    monkeypatch.setattr(tslp, "download", lambda langs: downloads.append(langs), raising=False)
    assert treesitter.parser_for("python") is not None
    assert downloads == []
