def _write(root: Path, rel: str, text: str) -> Path:
    path = root / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


@pytest.mark.parametrize("suffix", [".js", ".jsx", ".mjs", ".cjs"])
def test_js_discovery_and_jsx_matching_tsx(suffix):
    assert language_of(f"ui/view{suffix}") == "typescript"
    assert is_test_file(f"ui/view.test{suffix}")
    assert is_test_file(f"ui/view.spec{suffix}")

    js_entries, _ = entries_in_source(
        "typescript",
        """\
export const alpha = () => {
  const label = format("alpha");
  return <button title={label}>{label}</button>;
};
""",
        f"left{suffix}",
        f"left{suffix}",
    )
    tsx_entries, _ = entries_in_source(
        "typescript",
        """\
export const beta = () => {
  const text = format("beta");
  return <button title={text}>{text}</button>;
};
""",
        "right.tsx",
        "right.tsx",
    )
    found = find_duplicates(js_entries + tsx_entries, threshold=0.99)
    assert [(item.left.file, item.right.file, item.score) for item in found] == [
        (f"left{suffix}", "right.tsx", 1.0)
    ]


def test_generated_files_are_skipped_without_skipping_handwritten_mentions(tmp_path):
    body = "def alpha(xs):\n    out = transform(xs)\n    return finish(out)\n"
    _write(tmp_path, "a.py", body)
    _write(tmp_path, "b.py", "# @generated by tool\n" + body)
    _write(tmp_path, "c.go", "// Code generated by sqlc. DO NOT EDIT.\npackage p\nfunc F() int { return 1 }\n")
    _write(
        tmp_path,
        "handwritten.py",
        '# Mentions @generated and <auto-generated> in explanatory prose\ndef beta(xs):\n    marker = "@generated"\n    return marker\n',
    )
    _write(
        tmp_path,
        "multiline_str.py",
        '# Accepts /* as a path suffix.\ndef gamma(xs):\n    doc = """\n# @generated by a tool\n"""\n    return doc\n',
    )
    _write(
        tmp_path,
        "block_prose.ts",
        "/*\n * Mentions @generated and <auto-generated> in explanatory prose\n */\nexport function keepMe(x: number) { return x + 1; }\n",
    )
    _write(
        tmp_path,
        "gen.ps1",
        "<#\n@generated by tool\n#>\nfunction Get-Gen($x) { return $x + 1 }\n",
    )
    assert is_test_file("ui/view.test.JS")
    assert is_test_file("ui/view.spec.JSX")
    entries, warnings = scan_files(
        [
            tmp_path / "a.py",
            tmp_path / "b.py",
            tmp_path / "c.go",
            tmp_path / "handwritten.py",
            tmp_path / "multiline_str.py",
            tmp_path / "block_prose.ts",
            tmp_path / "gen.ps1",
        ],
        tmp_path,
        1,
        1,
    )
    assert warnings == []
    assert [e.file for e in entries] == ["a.py", "handwritten.py", "multiline_str.py", "block_prose.ts"]


def test_powershell_property_rename_matches_while_method_call_stays_distinct():
    p1, _ = entries_in_source(
        "powershell",
        "function Get-A($item) {\n  $v = $item.Total\n  return $item.Approve($v)\n}\n",
        "a.ps1",
        "a.ps1",
    )
    p2, _ = entries_in_source(
        "powershell",
        "function Get-B($row) {\n  $v = $row.Amount\n  return $row.Approve($v)\n}\n",
        "b.ps1",
        "b.ps1",
    )
    p3, _ = entries_in_source(
        "powershell",
        "function Get-C($row) {\n  $v = $row.Amount\n  return $row.Reject($v)\n}\n",
        "c.ps1",
        "c.ps1",
    )
    same = find_duplicates(p1 + p2, threshold=0.99)
    assert len(same) == 1 and same[0].score == 1.0
    diff = find_duplicates(p1 + p3, threshold=0.0)
    assert len(diff) == 1 and diff[0].score < 1.0


def test_mixed_prod_and_test_csproj_in_same_dir_keeps_production_files(tmp_path):
    _write(tmp_path, "Mix/Prod.csproj", '<Project Sdk="Microsoft.NET.Sdk" />\n')
    _write(
        tmp_path,
        "Mix/Mix.Tests.csproj",
        '<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><IsTestProject>true</IsTestProject></PropertyGroup></Project>\n',
    )
    src = _write(tmp_path, "Mix/Prod.cs", "class Prod { int F() => 1; }\n")
    assert not is_test_file(src)


def test_js_template_interpolation_preserves_embedded_calls():
    left, _ = entries_in_source(
        "typescript",
        "export function a(x) {\n  return `val=${approve(x)}`;\n}\n",
        "a.js",
        "a.js",
    )
    right, _ = entries_in_source(
        "typescript",
        "export function b(y) {\n  return `val=${reject(y)}`;\n}\n",
        "b.js",
        "b.js",
    )
    found = find_duplicates(left + right, threshold=0.0)
    assert len(found) == 1 and found[0].score < 1.0


